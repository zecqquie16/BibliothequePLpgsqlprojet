UNION ALL SELECT 'livre', count(*) FROM livre
UNION ALL SELECT 'emprunteur', count(*) FROM emprunteur
UNION ALL SELECT 'emprunt', count(*) FROM emprunt
UNION ALL SELECT 'reservation', count(*) FROM reservation
