   A executer UNE FOIS, en entier (DBeaver : Alt+X). Teste sur PostgreSQL 16.

   Convention (disponibilite) :
     livre.nb_exemplaires = nombre TOTAL d'exemplaires possedes par la bibliotheque.
     Un livre est "disponible" s'il reste au moins un exemplaire non emprunte, i.e.
        nb_exemplaires - (nombre d'emprunts EN COURS de ce livre) >= 1
     Un emprunt est "en cours" quand sa date_retour est NULL.
   ============================================================================ */

-- Suppression dans l'ordre inverse des dependances (rejouable)
DROP TABLE IF EXISTS reservation CASCADE;
DROP TABLE IF EXISTS emprunt     CASCADE;
DROP TABLE IF EXISTS livre       CASCADE;
DROP TABLE IF EXISTS emprunteur  CASCADE;
DROP TABLE IF EXISTS categorie   CASCADE;
DROP TABLE IF EXISTS auteur      CASCADE;

/* ----------------------------- Schema ------------------------------------- */

CREATE TABLE auteur (
    id_auteur INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom       VARCHAR(60) NOT NULL,
    pays      VARCHAR(40)
);

CREATE TABLE categorie (
    id_categorie INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle      VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE livre (
    id_livre       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titre          VARCHAR(120) NOT NULL,
    id_auteur      INT NOT NULL REFERENCES auteur(id_auteur),
    id_categorie   INT NOT NULL REFERENCES categorie(id_categorie),
    annee          INT,
    nb_exemplaires INT NOT NULL DEFAULT 1 CHECK (nb_exemplaires >= 0)
);

CREATE TABLE emprunteur (
    id_emprunteur    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom              VARCHAR(60) NOT NULL,
    date_inscription DATE NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE emprunt (
    id_emprunt    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_livre      INT NOT NULL REFERENCES livre(id_livre),
    id_emprunteur INT NOT NULL REFERENCES emprunteur(id_emprunteur),
    date_emprunt  DATE NOT NULL DEFAULT CURRENT_DATE,
    date_retour   DATE,                       -- NULL = emprunt en cours
    CONSTRAINT chk_dates CHECK (date_retour IS NULL OR date_retour >= date_emprunt)
);

CREATE TABLE reservation (
    id_reservation   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_livre         INT NOT NULL REFERENCES livre(id_livre),
    id_emprunteur    INT NOT NULL REFERENCES emprunteur(id_emprunteur),
    date_reservation DATE NOT NULL DEFAULT CURRENT_DATE,
    statut           VARCHAR(12) NOT NULL DEFAULT 'en attente'
                     CHECK (statut IN ('en attente','validée','annulée'))
);

